type e2eBuildRecorder struct {
	mu       sync.Mutex
	commands []string
	infos    []string
}

func (r *e2eBuildRecorder) emitter() *emitter {
	return &emitter{send: func(ev *pb.DeployEvent) error {
		l := ev.GetLog()
		if l == nil {
			return nil
		}
		r.mu.Lock()
		defer r.mu.Unlock()
		switch l.GetLevel() {
		case "command":
			r.commands = append(r.commands, l.GetText())
		default:
			r.infos = append(r.infos, l.GetText())
		}
		return nil
	}}
}

func (r *e2eBuildRecorder) joined() string {
	r.mu.Lock()
	defer r.mu.Unlock()
	return strings.Join(append(append([]string{}, r.commands...), r.infos...), "\n")
}

func e2eToolsBase(t *testing.T) string {
	t.Helper()
	base := filepath.Join(os.TempDir(), "deplo-agent-e2e-tools")
	if err := os.MkdirAll(base, 0o755); err != nil {
		t.Fatal(err)
	}
	return base
}

// End-to-end (real docker): a railpack build must go through the daemon's own BuildKit - plan generated by the host binary, executed by the railpack frontend selected with BUILDKIT_SYNTAX, and land a LABELLED image in the image store in one pass.
func TestE2E_RailpackBuildsLabelledImageWithoutBuildkitdContainer(t *testing.T) {
	ctx := context.Background()
	if !dockercli.Available(ctx) {
		t.Skip("docker not available")
	}
	if !dockercli.ImageExportOptsSupported(ctx) {
		t.Skip("railpack's frontend needs the containerd image store (mergeop); this daemon uses the classic store")
	}
	s := New(t.TempDir(), t.TempDir(), "/", e2eToolsBase(t))

	buildDir := t.TempDir()
	write := func(name, body string) {
		if err := os.WriteFile(filepath.Join(buildDir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("package.json", `{"name":"e2e-railpack","version":"1.0.0","scripts":{"build":"node -e \"require('fs').writeFileSync('baked.txt', process.env.NEXT_PUBLIC_API||'MISSING')\"","start":"node server.js"}}`)
	write("server.js", `require("http").createServer((_,r)=>r.end("ok")).listen(3000);`)

	const image = "deplo-test/railpack:e2e"
	const value = "https://api.example.test/v1"
	req := &pb.DeployRequest{
		Slug:      "railpacke2e",
		ProjectId: "prj_railpacke2e",
		ImageRef:  image,
		BuildKind: pb.BuildKind_BUILD_KIND_RAILPACK,
		BuildSpec: &pb.BuildSpec{Method: "railpack", Port: 3000},
		Env:       map[string]string{"NEXT_PUBLIC_API": value},
	}

	rec := &e2eBuildRecorder{}
	if !s.buildImage(ctx, req, buildDir, rec.emitter()) {
		t.Fatalf("railpack build failed; log:\n%s", rec.joined())
	}
	defer func() { _, _ = dockercli.Run(context.Background(), 60*time.Second, "rmi", "-f", image) }()

	labels, err := dockercli.Run(ctx, 30*time.Second, "image", "inspect", image,
		"--format", "{{index .Config.Labels \"deplo.managed\"}}/{{index .Config.Labels \"deplo.slug\"}}")
	if err != nil || labels.Code != 0 {
		t.Fatalf("inspect labels: %v %s", err, labels.Stderr)
	}
	if got := strings.TrimSpace(labels.Stdout); got != "true/railpacke2e" {
		t.Fatalf("labels = %q; want true/railpacke2e (frontend output must be labelled in one pass)", got)
	}

	baked, err := dockercli.Run(ctx, 60*time.Second, "run", "--rm", "--entrypoint", "cat", image, "/app/baked.txt")
	if err != nil || baked.Code != 0 {
		t.Fatalf("read baked file: %v %s", err, baked.Stderr)
	}
	if got := strings.TrimSpace(baked.Stdout); got != value {
		t.Fatalf("build-time env = %q; want %q", got, value)
	}

	log := rec.joined()
	for _, forbidden := range []string{"deplo-buildkitd-", "docker load", "buildctl", "apt-get"} {
		if strings.Contains(log, forbidden) {
			t.Fatalf("railpack still uses %q; log:\n%s", forbidden, log)
		}
	}
	ps, err := dockercli.Run(ctx, 30*time.Second, "ps", "-a", "--filter", "name=deplo-buildkitd-", "-q")
	if err == nil && strings.TrimSpace(ps.Stdout) != "" {
		t.Fatalf("a buildkitd container was left behind: %s", ps.Stdout)
	}

	if strings.Contains(strings.Join(rec.commands, "\n"), value) {
		t.Fatalf("build-env value leaked into a logged command: %v", rec.commands)
	}
}

// End-to-end (real docker): a build must ask for the fast image export exactly when the daemon can take it.
func TestE2E_BuildAsksForFastExportWhenSupported(t *testing.T) {
	ctx := context.Background()
	if !dockercli.Available(ctx) {
		t.Skip("docker not available")
	}
	s := New(t.TempDir(), t.TempDir(), "/", "")
	buildDir := t.TempDir()

	const image = "deplo-test/fastexport:e2e"
	req := &pb.DeployRequest{
		Slug:       "fastexport",
		ProjectId:  "prj_fastexport",
		ImageRef:   image,
		BuildKind:  pb.BuildKind_BUILD_KIND_DOCKERFILE,
		Dockerfile: &pb.DockerfileBuild{Generated: true, GeneratedDockerfile: "FROM busybox\nCMD [\"true\"]\n"},
	}

	rec := &e2eBuildRecorder{}
	if !s.buildImage(ctx, req, buildDir, rec.emitter()) {
		t.Fatalf("build failed; log:\n%s", rec.joined())
	}
	defer func() { _, _ = dockercli.Run(context.Background(), 30*time.Second, "rmi", "-f", image) }()

	cmds := strings.Join(rec.commands, "\n")
	if dockercli.ImageExportOptsSupported(ctx) {
		want := "--output type=image,name=" + image + ",compression=zstd,compression-level=1"
		if !strings.Contains(cmds, want) {
			t.Fatalf("containerd store present but the build did not ask for the fast export.\nwant: %s\ngot:  %s", want, cmds)
		}
	} else if !strings.Contains(cmds, "-t "+image) {
		t.Fatalf("no image exporter available, so the build must use -t; got: %s", cmds)
	}

	res, err := dockercli.Run(ctx, 30*time.Second, "image", "inspect", image, "--format", "{{.Id}}")
	if err != nil || res.Code != 0 {
		t.Fatalf("built image is not in the image store: %v %s", err, res.Stderr)
	}
}

// End-to-end (real docker): a static folder with an output directory and the single-page flag
// is served by Railpack with every unknown path answered by index.html.
func TestE2E_RailpackServesASinglePageApp(t *testing.T) {
	ctx := context.Background()
	if !dockercli.Available(ctx) {
		t.Skip("docker not available")
	}
	if !dockercli.ImageExportOptsSupported(ctx) {
		t.Skip("railpack's frontend needs the containerd image store (mergeop); this daemon uses the classic store")
	}
	const image, name = "deplo-agent-test/railpack-spa:e2e", "deplo-agent-test-railpack-spa"
	t.Cleanup(func() {
		_, _ = dockercli.Run(context.Background(), 30*time.Second, "rm", "-f", name)
		_, _ = dockercli.Run(context.Background(), 60*time.Second, "rmi", "-f", image)
	})
	buildDir := t.TempDir()
	mustWrite(t, filepath.Join(buildDir, "dist", "index.html"), "<h1>spa-shell</h1>\n")
	req := &pb.DeployRequest{
		Slug: "deplo-agent-test-railpack-spa", ProjectId: "prj_spa", ImageRef: image,
		BuildKind: pb.BuildKind_BUILD_KIND_RAILPACK,
		BuildSpec: &pb.BuildSpec{Method: "railpack", OutputDirectory: "dist", StaticSinglePageApp: true},
	}
	rec := &e2eBuildRecorder{}
	if !New(t.TempDir(), t.TempDir(), "/", e2eToolsBase(t)).buildImage(ctx, req, buildDir, rec.emitter()) {
		t.Fatalf("build failed; log:\n%s", rec.joined())
	}
	if run, err := dockercli.Run(ctx, 60*time.Second, "run", "-d", "--name", name, "-e", "PORT=8080", image); err != nil || run.Code != 0 {
		t.Fatalf("run: %v %s", err, run.Stderr)
	}
	var body string
	for i := 0; i < 30 && !strings.Contains(body, "spa-shell"); i++ {
		time.Sleep(time.Second)
		got, _ := dockercli.Run(ctx, 30*time.Second, "run", "--rm", "--network", "container:"+name, "busybox:1.37",
			"wget", "-qO-", "http://127.0.0.1:8080/some/client/route")
		body = got.Stdout
	}
	if !strings.Contains(body, "spa-shell") {
		t.Fatalf("an unknown path did not get index.html: %q; build log:\n%s", body, rec.joined())
	}
}

// End-to-end (real docker): with --error-missing-start a project railpack cannot start fails at
// prepare, and the result says where to set the start command.
func TestE2E_RailpackNamesAMissingStartCommand(t *testing.T) {
	ctx := context.Background()
	if !dockercli.Available(ctx) {
		t.Skip("docker not available")
	}
	buildDir := t.TempDir()
	mustWrite(t, filepath.Join(buildDir, "package.json"), `{"name":"lib","version":"1.0.0"}`)
	var res *pb.DeployResult
	rec := &e2eBuildRecorder{}
	e := &emitter{send: func(ev *pb.DeployEvent) error {
		if r := ev.GetResult(); r != nil {
			res = r
		}
		return rec.emitter().send(ev)
	}}
	req := &pb.DeployRequest{Slug: "deplo-agent-test-nostart", ProjectId: "prj_nostart", ImageRef: "deplo-agent-test/nostart:e2e",
		BuildKind: pb.BuildKind_BUILD_KIND_RAILPACK, BuildSpec: &pb.BuildSpec{Method: "railpack"}}
	if New(t.TempDir(), t.TempDir(), "/", e2eToolsBase(t)).buildImage(ctx, req, buildDir, e) {
		t.Fatal("a project with no start command built")
	}
	if res == nil || res.GetError() != "No start command detected. Set a Start command in Settings -> Build & output." {
		t.Fatalf("result = %v; log:\n%s", res, rec.joined())
	}
}

// End-to-end (real docker): install and build commands written as sh -c '...' run whole. railpack
// wraps both in its own sh -c '...', and the inner quotes used to cut them down to `sh -c <first word>`.
func TestE2E_RailpackRunsQuotedInstallAndBuildCommands(t *testing.T) {
	ctx := context.Background()
	if !dockercli.Available(ctx) {
		t.Skip("docker not available")
	}
	if !dockercli.ImageExportOptsSupported(ctx) {
		t.Skip("railpack's frontend needs the containerd image store (mergeop); this daemon uses the classic store")
	}
	const image = "deplo-agent-test/railpack-quotes:e2e"
	t.Cleanup(func() { _, _ = dockercli.Run(context.Background(), 60*time.Second, "rmi", "-f", image) })
	buildDir := t.TempDir()
	mustWrite(t, filepath.Join(buildDir, "package.json"), `{"name":"e2e-quotes","version":"1.0.0","scripts":{"start":"node server.js"}}`)
	mustWrite(t, filepath.Join(buildDir, "server.js"), `require("http").createServer((_,r)=>r.end("ok")).listen(3000);`)
	req := &pb.DeployRequest{
		Slug: "deplo-agent-test-railpack-quotes", ProjectId: "prj_quotes", ImageRef: image,
		BuildKind: pb.BuildKind_BUILD_KIND_RAILPACK,
		BuildSpec: &pb.BuildSpec{Method: "railpack", Port: 3000,
			InstallCommand: "sh -c 'mkdir -p node_modules && echo install > node_modules/.install-ran'",
			BuildCommand:   "sh -c 'echo one > a.txt && echo two > b.txt'"},
	}
	rec := &e2eBuildRecorder{}
	if !New(t.TempDir(), t.TempDir(), "/", e2eToolsBase(t)).buildImage(ctx, req, buildDir, rec.emitter()) {
		t.Fatalf("build failed; log:\n%s", rec.joined())
	}
	got, err := dockercli.Run(ctx, 60*time.Second, "run", "--rm", "--entrypoint", "cat", image,
		"/app/node_modules/.install-ran", "/app/a.txt", "/app/b.txt")
	if err != nil || got.Code != 0 || strings.Join(strings.Fields(got.Stdout), " ") != "install one two" {
		t.Fatalf("what the commands wrote: %q %s %v; build log:\n%s", got.Stdout, got.Stderr, err, rec.joined())
	}
}
